import pathlib
from playwright.sync_api import sync_playwright
root = pathlib.Path(__file__).resolve().parent
url = (root.parent / 'index.html').as_uri()
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={'width':1440,'height':900})
    errs=[]; pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('console', lambda m: m.type=='error' and errs.append(m.text))
    pg.goto(url); pg.wait_for_timeout(2600)
    pg.click('.add >> nth=0'); pg.click('.add >> nth=2'); pg.click('.tel-add >> nth=0'); pg.click('.join >> nth=1')
    pg.wait_for_timeout(700)
    print('count', pg.inner_text('#basket-count'))
    pg.click('#basket-btn'); pg.wait_for_timeout(300); print('panel', pg.inner_text('#basket-panel')[:300].replace('\n',' | '))
    pg.screenshot(path=str(root/'shots'/'i-basket.png'))
    pg.keyboard.press('Escape')
    pg.click('.pick >> nth=1'); pg.wait_for_timeout(800)
    pg.click('#book-submit'); pg.wait_for_timeout(400)
    print('errors', [pg.inner_text('#e-'+k) for k in ['name','email','date','time']])
    pg.screenshot(path=str(root/'shots'/'i-errors.png'))
