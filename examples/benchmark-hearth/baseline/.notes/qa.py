import pathlib, json
from playwright.sync_api import sync_playwright
root = pathlib.Path(__file__).resolve().parent
url = (root.parent / "index.html").as_uri()
out = root
with sync_playwright() as p:
    b = p.chromium.launch()
    errs = []
    for name, w, h in [("desktop",1440,900),("tablet",768,1024),("mobile",375,812)]:
        pg = b.new_page(viewport={"width":w,"height":h})
        pg.on("console", lambda m: m.type=="error" and errs.append(m.text))
        pg.on("pageerror", lambda e: errs.append(str(e)))
        pg.goto(url); pg.wait_for_timeout(1200)
        pg.screenshot(path=str(out/f"{name}-fold.png"))
        sw = pg.evaluate("document.documentElement.scrollWidth")
        print(name, "scrollWidth", sw)
        # full page: disable reveal hiding
        pg.evaluate("document.querySelectorAll('.pre').forEach(e=>e.classList.remove('pre'))"); pg.wait_for_timeout(900)
        pg.screenshot(path=str(out/f"{name}-full.png"), full_page=True)
        pg.close()
    pg = b.new_page(viewport={"width":375,"height":812})
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(url); pg.wait_for_timeout(500)
    pg.click(".burger"); pg.wait_for_timeout(400)
    pg.screenshot(path=str(out/"mobile-menu.png"))
    print("menu expanded", pg.get_attribute(".burger","aria-expanded"))
    pg.keyboard.press("Escape")
    print("after esc", pg.get_attribute(".burger","aria-expanded"))
    pg.click("[data-filter=VG]")
    print("filter VG visible", pg.evaluate("[...document.querySelectorAll('.dish')].filter(d=>!d.hidden).length"), pg.text_content("#filterStatus"))
    pg.click("[data-filter=GF]")
    print("filter GF visible", pg.evaluate("[...document.querySelectorAll('.dish')].filter(d=>!d.hidden).length"))
    pg.click("#bookForm button[type=submit]")
    print("summary", pg.text_content("#formSummary"))
    print("date options", pg.evaluate("[...document.querySelectorAll('#f-date option')].slice(1).map(o=>o.text)"))
    print("times", pg.evaluate("[...document.querySelectorAll('#f-time option')].slice(1).map(o=>o.value)"))
    pg.locator("#book").scroll_into_view_if_needed()
    pg.screenshot(path=str(out/"mobile-form-errors.png"))
    pg.fill("#f-name","Alex Test"); pg.fill("#f-email","bad")
    pg.locator("#f-email").blur()
    print("email invalid", pg.evaluate("document.getElementById('f-email').closest('.field').classList.contains('invalid')"))
    pg.fill("#f-email","alex@example.com")
    pg.click("label[for=p4]")
    pg.select_option("#f-date", index=3); pg.select_option("#f-time","19:30")
    pg.fill("#f-notes","No nuts")
    pg.click("#bookForm button[type=submit]"); pg.wait_for_timeout(300)
    print("success visible", pg.is_visible("#success"), pg.text_content("#success dl"))
    pg.screenshot(path=str(out/"mobile-success.png"))
    pg.click("#q2"); pg.wait_for_timeout(400)
    print("acc", pg.get_attribute("#q2","aria-expanded"), pg.is_visible("#a2 p"))
    print("errors", errs)
    b.close()
