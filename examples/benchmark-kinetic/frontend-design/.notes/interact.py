import asyncio
from playwright.async_api import async_playwright
U='http://127.0.0.1:18942/index.html'
async def m():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        pg=await b.new_page(viewport={'width':375,'height':812})
        errs=[]; pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('console', lambda c: errs.append(c.text) if c.type=='error' else None)
        await pg.goto(U, wait_until='networkidle'); await pg.wait_for_timeout(1200)
        await pg.click('.menu-toggle'); await pg.wait_for_timeout(900)
        print('menu open', await pg.evaluate("[document.querySelector('.menu-toggle').getAttribute('aria-expanded'), getComputedStyle(document.querySelector('#mobile-menu')).visibility, document.activeElement.textContent.trim().slice(0,10)]"))
        await pg.screenshot(path='.notes/shots/i-menu.png')
        await pg.click('#mobile-menu a[href="#work"]'); await pg.wait_for_timeout(1500)
        print('menu closed+scrolled', await pg.evaluate("[document.querySelector('.menu-toggle').getAttribute('aria-expanded'), Math.round(document.querySelector('#work').getBoundingClientRect().top)]"))
        await pg.click('.svc-item[data-i="2"] .svc-title'); await pg.wait_for_timeout(900)
        print('svc mobile', await pg.evaluate("[document.querySelector('.svc-item.is-active').dataset.i, document.querySelector('.svc-visual.is-active').dataset.v]"))
        await pg.click('[data-case="1"]'); await pg.wait_for_timeout(700)
        print('dialog', await pg.evaluate("[document.querySelector('#caseDialog').open, document.querySelector('#caseTitle').textContent]"))
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        print('dialog closed', await pg.evaluate("document.querySelector('#caseDialog').open"))
        await pg.evaluate("document.querySelector('#brief').scrollIntoView()")
        await pg.click('#brief button[type=submit]'); await pg.wait_for_timeout(300)
        print('invalid', await pg.evaluate("[document.querySelector('#formStatus').textContent, document.activeElement.id, document.querySelector('#e-email').textContent]"))
        await pg.fill('#f-name','Test Person'); await pg.fill('#f-email','test@example.com'); await pg.fill('#f-msg','We need a new website for our launch.')
        await pg.evaluate("document.querySelector('input[value=Website]').click()")
        await pg.evaluate("window.__href=null; const d=Object.getOwnPropertyDescriptor(Location.prototype,'href');")
        reqs=[]
        pg.on('framenavigated', lambda f: reqs.append(f.url))
        await pg.click('#brief button[type=submit]'); await pg.wait_for_timeout(500)
        print('valid', await pg.evaluate("document.querySelector('#formStatus').textContent"))
        await pg.screenshot(path='.notes/shots/i-form.png')
        await pg.evaluate("document.querySelector('.reel').scrollIntoView()"); await pg.wait_for_timeout(500)
        await pg.click('#reelBtn'); await pg.wait_for_timeout(200)
        print('reel', await pg.evaluate("[document.querySelector('#reelBtn').getAttribute('aria-pressed'), document.querySelector('.rb-label').textContent]"))
        print('errors', errs)
        # desktop: services click + keyboard focus
        pg2=await b.new_page(viewport={'width':1440,'height':900})
        await pg2.goto(U, wait_until='networkidle'); await pg2.wait_for_timeout(1500)
        await pg2.keyboard.press('Tab'); await pg2.keyboard.press('Tab')
        print('focus', await pg2.evaluate("[document.activeElement.className, getComputedStyle(document.activeElement).outlineStyle]"))
        await pg2.evaluate("document.querySelector('.svc-scroll').scrollIntoView()"); await pg2.wait_for_timeout(1500)
        await pg2.click('.svc-item[data-i="3"] .svc-title'); await pg2.wait_for_timeout(2200)
        print('svc desk', await pg2.evaluate("[document.querySelector('.svc-item.is-active').dataset.i, document.querySelectorAll('.svc-visual.is-active').length]"))
        await b.close()
asyncio.run(m())
