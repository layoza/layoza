import asyncio
from playwright.async_api import async_playwright
URL="examples/benchmark-ledgerline/impeccable/index.html"
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); pg=await b.new_page(viewport={"width":1440,"height":900})
        await pg.goto(URL); await pg.evaluate("document.fonts.ready")
        await pg.fill("#clients-n","100"); await pg.fill("#tx-n","90")
        print("est", await pg.inner_text("#hours"), "|", await pg.inner_text("#words"), "|", await pg.inner_text("#lines"))
        await pg.fill("#tx-n",""); print("est-empty err:", await pg.inner_text("#tx-err"))
        await pg.fill("#tx-n","90")
        await pg.click("label[for=bill-y]"); print("yearly", await pg.inner_text(".plan .amt"), await pg.inner_text(".plan [data-billed]"))
        await pg.click("label[for=bill-m]"); print("monthly", await pg.inner_text(".plan .amt"))
        await pg.click(".faq summary >> nth=0"); await pg.wait_for_timeout(400)
        await pg.click(".faq summary >> nth=1"); await pg.wait_for_timeout(400)
        print("faq open", await pg.evaluate("[...document.querySelectorAll('.faq details')].map(d=>d.open)"))
        await pg.fill("#q-email","bad"); await pg.click("#quick button"); print("hero err:", await pg.inner_text("#q-err"))
        await pg.fill("#q-email","sam@firm.co.uk"); await pg.click("#quick button"); await pg.wait_for_timeout(800)
        print("prefill", await pg.input_value("#f-email"), "focus", await pg.evaluate("document.activeElement.id"))
        await pg.click("#signup button[type=submit]")
        print("errs", [await pg.inner_text(f"#m-{k}") for k in ["name","email","firm","size"]])
        await pg.fill("#f-name","Sam Hale"); await pg.fill("#f-firm","Hale & Co"); await pg.select_option("#f-size","3-10")
        await pg.click("#signup button[type=submit]"); await pg.wait_for_timeout(1000)
        print("success", await pg.is_visible("#success"), await pg.inner_text("#s-title"))
        m=await b.new_page(viewport={"width":375,"height":812}); await m.goto(URL)
        await m.click(".menu-btn"); await m.wait_for_timeout(300)
        print("menu", await m.get_attribute(".menu-btn","aria-expanded"), await m.is_visible("#drawer .d-link"))
        await m.screenshot(path=".impeccable/review/mobile-menu.png")
        await m.keyboard.press("Escape"); print("esc", await m.get_attribute(".menu-btn","aria-expanded"))
        await b.close()
asyncio.run(main())
