import pathlib
from playwright.sync_api import sync_playwright
here = pathlib.Path(__file__).resolve().parent
url = (here.parent / "index.html").as_uri()
shots = here / "shots"
with sync_playwright() as p:
    b = p.chromium.launch(args=["--use-angle=swiftshader","--enable-unsafe-swiftshader"])
    # form + accordion + drag on desktop
    pg = b.new_page(viewport={"width":1440,"height":900})
    errs=[]; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(url, wait_until="networkidle"); pg.wait_for_timeout(1500)
    pg.mouse.move(900,500); pg.mouse.down(); pg.mouse.move(1100,500, steps=10); pg.mouse.up()
    pg.locator("#test-ride").scroll_into_view_if_needed()
    pg.click("#booking button[type=submit]")
    print("errors after empty submit:", [pg.text_content(f"#e-{n}") for n in ["name","email","city","date"]])
    print("focused:", pg.evaluate("document.activeElement.id"))
    pg.screenshot(path=str(shots/"form-errors.png"))
    pg.fill("#f-name","Jo Bloggs"); pg.fill("#f-email","jo@bad"); pg.locator("#f-email").blur()
    print("email err:", pg.text_content("#e-email"))
    pg.fill("#f-email","jo@example.com"); pg.select_option("#f-city","Bath")
    pg.fill("#f-date", pg.evaluate("document.getElementById('f-date').min"))
    pg.click("#booking button[type=submit]")
    print("success visible:", pg.is_visible("#booking-success"), pg.text_content("#success-text"))
    pg.screenshot(path=str(shots/"form-success.png"))
    pg.click("details:nth-of-type(2) summary")
    print("accordion open:", pg.evaluate("document.querySelectorAll('details')[1].open"))
    pg.check("#c-graphite"); pg.click("#add-basket"); print("basket:", pg.text_content("#basket-status"))
    print("page errors:", errs)
    pg.close()
    # mobile nav
    pg = b.new_page(viewport={"width":375,"height":812})
    pg.goto(url, wait_until="networkidle"); pg.wait_for_timeout(800)
    pg.click(".menu-btn"); pg.wait_for_timeout(200)
    print("menu expanded:", pg.get_attribute(".menu-btn","aria-expanded"), pg.is_visible("#mobile-nav"))
    pg.screenshot(path=str(shots/"mobile-menu.png"))
    pg.keyboard.press("Escape"); print("menu closed:", pg.is_hidden("#mobile-nav"))
    pg.close()
    # reduced motion
    ctx = b.new_context(viewport={"width":1440,"height":900}, reduced_motion="reduce")
    pg = ctx.new_page(); pg.goto(url, wait_until="networkidle"); pg.wait_for_timeout(1200)
    pg.screenshot(path=str(shots/"reduced-hero.png")); ctx.close()
    # no WebGL
    b2 = p.chromium.launch(args=["--disable-webgl","--disable-3d-apis"])
    pg = b2.new_page(viewport={"width":1440,"height":900}); pg.goto(url, wait_until="networkidle"); pg.wait_for_timeout(800)
    print("no-webgl class:", pg.evaluate("document.documentElement.classList.contains('no-webgl')"))
    pg.screenshot(path=str(shots/"nowebgl-hero.png"))
    pg.evaluate("document.querySelector('[data-step=battery]').scrollIntoView({block:'center'})"); pg.wait_for_timeout(300)
    pg.screenshot(path=str(shots/"nowebgl-battery.png"))
    pg.check("#c-clay"); pg.evaluate("document.querySelector('[data-step=colour]').scrollIntoView({block:'center'})"); pg.wait_for_timeout(300)
    pg.screenshot(path=str(shots/"nowebgl-colour.png"))
    b2.close(); b.close()
