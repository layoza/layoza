use crate::dna::SiteDna;
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AdapterOutput {
    pub framework: String,
    pub files: BTreeMap<String, String>,
    pub notes: Vec<String>,
}

/// Generates framework-native files for a section or page while strictly preserving the project's chosen framework and Site DNA tokens.
pub fn generate_framework_artifact(
    framework: &str,
    section_title: &str,
    section_subtitle: &str,
    cta_label: &str,
    dna: &SiteDna,
) -> AdapterOutput {
    let fw = framework.trim().to_ascii_lowercase();
    let bg = dna
        .colors
        .iter()
        .find(|c| c.name.contains("bg") || c.name.contains("background"))
        .map(|c| c.value.as_str())
        .unwrap_or("#F8F7F4");
    let fg = dna
        .colors
        .first()
        .map(|c| c.value.as_str())
        .unwrap_or("#141619");
    let accent = dna
        .colors
        .iter()
        .find(|c| c.name.contains("accent") || c.name.contains("primary") || c.name.contains("cta"))
        .map(|c| c.value.as_str())
        .unwrap_or("#1D4ED8");
    let display_font = dna
        .typography
        .first()
        .map(|t| t.font_family.as_str())
        .unwrap_or("Instrument Serif, Georgia, serif");
    let body_font = dna
        .typography
        .get(1)
        .map(|t| t.font_family.as_str())
        .unwrap_or("Plus Jakarta Sans, system-ui, sans-serif");

    let mut files = BTreeMap::new();
    let mut notes = Vec::new();

    match fw.as_str() {
        "wordpress" | "wordpress-gutenberg" | "gutenberg" => {
            // Native WordPress Gutenberg Block Theme (`theme.json` v3 + `patterns/*.php` + `templates/index.html` + `style.css`)
            let theme_json = format!(
                r##"{{
  "$schema": "https://schemas.wp.org/trunk/theme.json",
  "version": 3,
  "settings": {{
    "appearanceTools": true,
    "layout": {{
      "contentSize": "840px",
      "wideSize": "1280px"
    }},
    "spacing": {{
      "units": ["px", "rem", "vh", "vw", "%"]
    }},
    "color": {{
      "palette": [
        {{ "slug": "canvas", "color": "{bg}", "name": "Canvas Background" }},
        {{ "slug": "ink", "color": "{fg}", "name": "Primary Ink" }},
        {{ "slug": "accent", "color": "{accent}", "name": "Brand Accent" }}
      ]
    }},
    "typography": {{
      "fluid": true,
      "fontFamilies": [
        {{ "slug": "display", "name": "Display", "fontFamily": "{display_font}" }},
        {{ "slug": "body", "name": "Body", "fontFamily": "{body_font}" }}
      ]
    }}
  }},
  "styles": {{
    "color": {{
      "background": "var(--wp--preset--color--canvas)",
      "text": "var(--wp--preset--color--ink)"
    }},
    "typography": {{
      "fontFamily": "var(--wp--preset--font-family--body)",
      "lineHeight": "1.6"
    }}
  }}
}}"##
            );

            let pattern_php = format!(
                r##"<?php
/**
 * Title: {section_title}
 * Slug: layoza/hero-section
 * Categories: featured, banner
 * Viewport Width: 1280
 */
?>
<!-- wp:group {{"align":"full","backgroundColor":"canvas","textColor":"ink","layout":{{"type":"constrained"}}}} -->
<section class="wp-block-group alignfull has-ink-color has-canvas-background-color has-text-color has-background" style="padding-top:5rem;padding-bottom:5rem">
  <!-- wp:heading {{"level":1,"fontFamily":"display"}} -->
  <h1 class="wp-block-heading has-display-font-family">{section_title}</h1>
  <!-- /wp:heading -->

  <!-- wp:paragraph -->
  <p>{section_subtitle}</p>
  <!-- /wp:paragraph -->

  <!-- wp:buttons -->
  <div class="wp-block-buttons">
    <!-- wp:button {{"backgroundColor":"accent"}} -->
    <div class="wp-block-button"><a class="wp-block-button__link has-accent-background-color has-background wp-element-button" href="#Action">{cta_label}</a></div>
    <!-- /wp:button -->
  </div>
  <!-- /wp:buttons -->
</section>
<!-- /wp:group -->
"##
            );

            let style_css = format!(
                r##"/*
Theme Name: {} Block Theme
Description: Native WordPress Gutenberg Block Theme generated by Layoza with theme.json v3 and reduced-motion accessibility.
Version: 1.0.0
Requires at least: 6.6
Tested up to: 6.7
License: MIT
*/
:focus-visible {{
  outline: 2px solid var(--wp--preset--color--accent, {accent});
  outline-offset: 3px;
}}
@media (prefers-reduced-motion: reduce) {{
  *, *::before, *::after {{
    animation-duration: 0.01ms !important;
    transition-duration: 0.01ms !important;
    scroll-behavior: auto !important;
  }}
}}
"##,
                dna.project_name
            );

            files.insert("theme.json".into(), theme_json);
            files.insert("patterns/hero-section.php".into(), pattern_php);
            files.insert(
                "templates/index.html".into(),
                "<!-- wp:pattern {\"slug\":\"layoza/hero-section\"} /-->\n".into(),
            );
            files.insert("style.css".into(), style_css);
            notes.push("Generated native WordPress Gutenberg Block Theme (`theme.json` v3, PHP block pattern, HTML template, `style.css`).".into());
        }
        "astro" => {
            let astro_code = format!(
                r##"---
// Native Astro Component (Zero-JS by default; progressive WAAPI reveal honoring prefers-reduced-motion)
interface Props {{
  title?: string;
  subtitle?: string;
  ctaLabel?: string;
}}
const {{
  title = "{section_title}",
  subtitle = "{section_subtitle}",
  ctaLabel = "{cta_label}"
}} = Astro.props;
---
<section class="layoza-section" aria-labelledby="layoza-heading">
  <div class="layoza-container">
    <h1 id="layoza-heading" class="layoza-title">{{title}}</h1>
    <p class="layoza-subtitle">{{subtitle}}</p>
    <div class="layoza-actions">
      <a href="#explore" class="layoza-cta">{{ctaLabel}}</a>
    </div>
  </div>
</section>

<style>
  .layoza-section {{
    background-color: var(--color-bg, {bg});
    color: var(--color-fg, {fg});
    font-family: {body_font};
    padding: clamp(3.5rem, 8vw, 6.5rem) 1.5rem;
  }}
  .layoza-container {{
    max-width: 1200px;
    margin: 0 auto;
  }}
  .layoza-title {{
    font-family: {display_font};
    font-size: clamp(2.25rem, 4.5vw, 4rem);
    line-height: 1.08;
    letter-spacing: -0.02em;
    margin: 0 0 1rem;
  }}
  .layoza-subtitle {{
    font-size: 1.125rem;
    line-height: 1.65;
    max-width: 62ch;
    margin: 0 0 2rem;
  }}
  .layoza-cta {{
    display: inline-flex;
    align-items: center;
    padding: 0.85rem 1.5rem;
    background: var(--color-accent, {accent});
    color: #ffffff;
    font-weight: 600;
    border-radius: 8px;
    text-decoration: none;
    transition: transform 180ms cubic-bezier(0.22, 1, 0.36, 1);
  }}
  .layoza-cta:focus-visible {{
    outline: 2px solid var(--color-accent, {accent});
    outline-offset: 3px;
  }}
  @media (prefers-reduced-motion: reduce) {{
    .layoza-cta {{
      transition: none !important;
    }}
  }}
</style>
"##
            );
            files.insert("src/components/LayozaSection.astro".into(), astro_code);
            notes.push("Generated native `.astro` component with scoped CSS and zero unnecessary client-side JS.".into());
        }
        "react" | "nextjs" => {
            let is_next = fw == "nextjs";
            let target_file = if is_next {
                "app/components/LayozaSection.tsx"
            } else {
                "src/components/LayozaSection.tsx"
            };
            let tsx = format!(
                r##"import React from "react";

export interface LayozaSectionProps {{
  title?: string;
  subtitle?: string;
  ctaLabel?: string;
  ctaHref?: string;
}}

export function LayozaSection({{
  title = "{section_title}",
  subtitle = "{section_subtitle}",
  ctaLabel = "{cta_label}",
  ctaHref = "#get-started",
}}: LayozaSectionProps) {{
  return (
    <section
      aria-labelledby="layoza-section-heading"
      style={{{{
        backgroundColor: "var(--color-bg, {bg})",
        color: "var(--color-fg, {fg})",
        fontFamily: "{body_font}",
        padding: "clamp(3.5rem, 8vw, 6.5rem) 1.5rem",
      }}}}
    >
      <div style={{{{ maxWidth: "1200px", margin: "0 auto" }}}}>
        <h1
          id="layoza-section-heading"
          style={{{{
            fontFamily: "{display_font}",
            fontSize: "clamp(2.25rem, 4.5vw, 4rem)",
            lineHeight: 1.08,
            letterSpacing: "-0.02em",
            marginBottom: "1rem",
          }}}}
        >
          {{title}}
        </h1>
        <p style={{{{ fontSize: "1.125rem", lineHeight: 1.65, maxWidth: "62ch", marginBottom: "2rem" }}}}>
          {{subtitle}}
        </p>
        <a
          href={{ctaHref}}
          style={{{{
            display: "inline-flex",
            alignItems: "center",
            padding: "0.85rem 1.5rem",
            backgroundColor: "var(--color-accent, {accent})",
            color: "#ffffff",
            borderRadius: "8px",
            fontWeight: 600,
            textDecoration: "none",
          }}}}
        >
          {{ctaLabel}}
        </a>
      </div>
    </section>
  );
}}
"##
            );
            files.insert(target_file.into(), tsx);
            notes.push(format!("Generated native {} TypeScript component preserving CSS variable tokens.", fw));
        }
        "vue" | "nuxt" => {
            let vue_sfc = format!(
                r##"<script setup lang="ts">
withDefaults(defineProps<{{
  title?: string;
  subtitle?: string;
  ctaLabel?: string;
}}>(), {{
  title: "{section_title}",
  subtitle: "{section_subtitle}",
  ctaLabel: "{cta_label}",
}});
</script>

<template>
  <section class="layoza-section" aria-labelledby="layoza-vue-title">
    <div class="layoza-inner">
      <h1 id="layoza-vue-title">{{{{ title }}}}</h1>
      <p>{{{{ subtitle }}}}</p>
      <a href="#action" class="layoza-btn">{{{{ ctaLabel }}}}</a>
    </div>
  </section>
</template>

<style scoped>
.layoza-section {{
  background: var(--color-bg, {bg});
  color: var(--color-fg, {fg});
  font-family: {body_font};
  padding: clamp(3.5rem, 8vw, 6.5rem) 1.5rem;
}}
.layoza-inner {{ max-width: 1200px; margin: 0 auto; }}
h1 {{ font-family: {display_font}; font-size: clamp(2.25rem, 4.5vw, 4rem); line-height: 1.08; }}
.layoza-btn {{
  display: inline-flex;
  padding: 0.85rem 1.5rem;
  background: var(--color-accent, {accent});
  color: #fff;
  border-radius: 8px;
  text-decoration: none;
}}
</style>
"##
            );
            files.insert("components/LayozaSection.vue".into(), vue_sfc);
            notes.push("Generated Vue 3 / Nuxt `<script setup>` SFC.".into());
        }
        "svelte" | "sveltekit" => {
            let svelte_code = format!(
                r##"<script lang="ts">
  export let title = "{section_title}";
  export let subtitle = "{section_subtitle}";
  export let ctaLabel = "{cta_label}";
</script>

<section class="layoza-section" aria-labelledby="layoza-svelte-title">
  <div class="layoza-inner">
    <h1 id="layoza-svelte-title">{{title}}</h1>
    <p>{{subtitle}}</p>
    <a href="#action" class="layoza-btn">{{ctaLabel}}</a>
  </div>
</section>

<style>
  .layoza-section {{
    background: var(--color-bg, {bg});
    color: var(--color-fg, {fg});
    font-family: {body_font};
    padding: clamp(3.5rem, 8vw, 6.5rem) 1.5rem;
  }}
  .layoza-inner {{ max-width: 1200px; margin: 0 auto; }}
  h1 {{ font-family: {display_font}; font-size: clamp(2.25rem, 4.5vw, 4rem); line-height: 1.08; }}
  .layoza-btn {{
    display: inline-flex;
    padding: 0.85rem 1.5rem;
    background: var(--color-accent, {accent});
    color: #fff;
    border-radius: 8px;
    text-decoration: none;
  }}
</style>
"##
            );
            files.insert("src/lib/components/LayozaSection.svelte".into(), svelte_code);
            notes.push("Generated Svelte / SvelteKit component.".into());
        }
        "elementor" => {
            // Actual Elementor Flexbox Container JSON schema (never React JSX!)
            let elementor_json = format!(
                r##"{{
  "version": "0.4",
  "title": "{section_title}",
  "type": "section",
  "content": [
    {{
      "id": "layoza_c1",
      "elType": "container",
      "settings": {{
        "content_width": "boxed",
        "background_background": "classic",
        "background_color": "{bg}",
        "padding": {{ "unit": "px", "top": "80", "right": "24", "bottom": "80", "left": "24", "isLinked": false }}
      }},
      "elements": [
        {{
          "id": "layoza_h1",
          "elType": "widget",
          "widgetType": "heading",
          "settings": {{
            "title": "{section_title}",
            "header_size": "h1",
            "title_color": "{fg}"
          }},
          "elements": []
        }},
        {{
          "id": "layoza_p1",
          "elType": "widget",
          "widgetType": "text-editor",
          "settings": {{
            "editor": "<p>{section_subtitle}</p>",
            "text_color": "{fg}"
          }},
          "elements": []
        }},
        {{
          "id": "layoza_b1",
          "elType": "widget",
          "widgetType": "button",
          "settings": {{
            "text": "{cta_label}",
            "background_color": "{accent}"
          }},
          "elements": []
        }}
      ]
    }}
  ]
}}"##
            );
            files.insert("elementor/layoza-section-template.json".into(), elementor_json);
            notes.push("Generated native Elementor v0.4 container/widget JSON template structure.".into());
        }
        "bricks" => {
            // Actual Bricks Builder flat parent/children element JSON structure
            let bricks_json = format!(
                r##"{{
  "content": [
    {{
      "id": "lyzsec",
      "name": "section",
      "parent": 0,
      "children": ["lyzcnt"],
      "settings": {{
        "_background": {{ "color": {{ "hex": "{bg}" }} }},
        "_padding": {{ "top": "80", "bottom": "80", "left": "24", "right": "24" }}
      }}
    }},
    {{
      "id": "lyzcnt",
      "name": "container",
      "parent": "lyzsec",
      "children": ["lyzhdg", "lyztxt", "lyzbtn"],
      "settings": {{ "_width": "1200px" }}
    }},
    {{
      "id": "lyzhdg",
      "name": "heading",
      "parent": "lyzcnt",
      "children": [],
      "settings": {{ "text": "{section_title}", "tag": "h1" }}
    }},
    {{
      "id": "lyztxt",
      "name": "text-basic",
      "parent": "lyzcnt",
      "children": [],
      "settings": {{ "text": "{section_subtitle}", "tag": "p" }}
    }},
    {{
      "id": "lyzbtn",
      "name": "button",
      "parent": "lyzcnt",
      "children": [],
      "settings": {{ "text": "{cta_label}", "style": "primary" }}
    }}
  ]
}}"##
            );
            files.insert("bricks/layoza-section-template.json".into(), bricks_json);
            notes.push("Generated native Bricks Builder flat ID/parent/children JSON template.".into());
        }
        "shopify" | "shopify-liquid" | "liquid" => {
            let liquid = format!(
                r##"<section class="layoza-shopify-section" style="background:{{{{ section.settings.bg_color }}}};color:{{{{ section.settings.text_color }}}};padding:5rem 1.5rem;">
  <div style="max-width:1200px;margin:0 auto;">
    <h1>{{{{ section.settings.heading | escape }}}}</h1>
    <p>{{{{ section.settings.subheading | escape }}}}</p>
    <a href="{{{{ section.settings.button_link }}}}" class="layoza-liquid-btn" style="background:{accent};color:#fff;padding:0.85rem 1.5rem;border-radius:8px;display:inline-flex;text-decoration:none;">
      {{{{ section.settings.button_label | escape }}}}
    </a>
  </div>
</section>

{{% schema %}}
{{
  "name": "Layoza Hero Section",
  "tag": "section",
  "settings": [
    {{ "type": "text", "id": "heading", "label": "Heading", "default": "{section_title}" }},
    {{ "type": "textarea", "id": "subheading", "label": "Subheading", "default": "{section_subtitle}" }},
    {{ "type": "text", "id": "button_label", "label": "Button Label", "default": "{cta_label}" }},
    {{ "type": "url", "id": "button_link", "label": "Button Link" }},
    {{ "type": "color", "id": "bg_color", "label": "Background", "default": "{bg}" }},
    {{ "type": "color", "id": "text_color", "label": "Text Color", "default": "{fg}" }}
  ],
  "presets": [{{ "name": "Layoza Hero Section" }}]
}}
{{% endschema %}}
"##
            );
            files.insert("sections/layoza-hero.liquid".into(), liquid);
            notes.push("Generated Shopify Online Store 2.0 `.liquid` section with valid `{% schema %}`.".into());
        }
        _ => {
            // Default: Semantic HTML5 + CSS Custom Properties + Accessible Reduced-Motion JS
            let html = format!(
                r##"<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>{section_title}</title>
  <style>
    :root {{
      --color-bg: {bg};
      --color-fg: {fg};
      --color-accent: {accent};
      --font-display: {display_font};
      --font-body: {body_font};
    }}
    *, *::before, *::after {{ box-sizing: border-box; }}
    body {{
      margin: 0;
      background-color: var(--color-bg);
      color: var(--color-fg);
      font-family: var(--font-body);
      line-height: 1.6;
      overflow-x: clip;
    }}
    .layoza-hero {{
      max-width: 1200px;
      margin: 0 auto;
      padding: clamp(4rem, 9vw, 7rem) 1.5rem;
    }}
    .layoza-hero h1 {{
      font-family: var(--font-display);
      font-size: clamp(2.5rem, 5vw, 4.25rem);
      line-height: 1.06;
      letter-spacing: -0.025em;
      margin: 0 0 1.25rem;
    }}
    .layoza-hero p {{
      font-size: 1.125rem;
      max-width: 62ch;
      margin: 0 0 2rem;
    }}
    .layoza-cta {{
      display: inline-flex;
      align-items: center;
      padding: 0.85rem 1.6rem;
      background-color: var(--color-accent);
      color: #ffffff;
      border-radius: 8px;
      font-weight: 600;
      text-decoration: none;
      transition: transform 200ms cubic-bezier(0.22, 1, 0.36, 1);
    }}
    .layoza-cta:hover {{ transform: translateY(-2px); }}
    :focus-visible {{
      outline: 2px solid var(--color-accent);
      outline-offset: 3px;
    }}
    @media (prefers-reduced-motion: reduce) {{
      *, *::before, *::after {{
        animation-duration: 0.01ms !important;
        transition-duration: 0.01ms !important;
        scroll-behavior: auto !important;
      }}
    }}
  </style>
</head>
<body>
  <main>
    <section class="layoza-hero" aria-labelledby="hero-title">
      <h1 id="hero-title">{section_title}</h1>
      <p>{section_subtitle}</p>
      <a class="layoza-cta" href="#action">{cta_label}</a>
    </section>
  </main>
</body>
</html>
"##
            );
            files.insert("index.html".into(), html);
            notes.push("Generated semantic HTML5 + CSS Custom Properties artifact with WCAG 2.2 AA and reduced-motion safeguards.".into());
        }
    }

    AdapterOutput {
        framework: fw,
        files,
        notes,
    }
}
